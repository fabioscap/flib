#include <ctime>
#include <memory>
#include <random>

#include "fodom/common.h"

// generate an SE(3) trajectory
// and produce imu measurements
namespace synthetic {

using fodom::IMUMeasurement;
using fodom::Isometry3_;
using fodom::Scalar;
using fodom::Vector3_;

// base class for synthetic trajectory
class Trajectory {
 public:
  Trajectory(Scalar T) : T_(T) {};

  inline Scalar T() const { return T_; }

  // generate the ground truth trajectory (isometry and velocity) and
  // measurements
  virtual void generateData(
      Scalar freq,
      std::vector<std::tuple<IMUMeasurement<Scalar>, Vector3_<Scalar>,
                             Isometry3_<Scalar>>>& data) const = 0;

 protected:
  Scalar T_;  // The duration of the trajectory
};

// the trajectories must have positive velocity always
// planar trajectory in which the rigid body is always tangent to the path
class SE3PlanarTrajectory : public Trajectory {
 public:
  SE3PlanarTrajectory(Scalar T) : Trajectory(T) {};
  // generate the ground truth trajectory (isometry and velocity) and
  // measurements
  virtual void generateData(
      Scalar freq,
      std::vector<std::tuple<IMUMeasurement<Scalar>, Vector3_<Scalar>,
                             Isometry3_<Scalar>>>& data) const override;

 protected:
  virtual void sampleTrajectory(Scalar t, Vector3_<Scalar>& pos,
                                Vector3_<Scalar>& vel,
                                Vector3_<Scalar>& acc) const {};

  // The frame is always tangent to the curve with its x-axis,
  // and the z-axis always points up (you can add rotation if needed).
  void getPoseMeasurement(Scalar t, Isometry3_<Scalar>& pose,
                          Vector3_<Scalar>& vel,
                          IMUMeasurement<Scalar>& measurement) const;
};

class SE3SineTrajectory : public SE3PlanarTrajectory {
 public:
  SE3SineTrajectory(Scalar T) : SE3PlanarTrajectory(T) {}

 protected:
  void sampleTrajectory(Scalar t, Vector3_<Scalar>& pos, Vector3_<Scalar>& vel,
                        Vector3_<Scalar>& acc) const override;
};
class SE3EightTrajectory : public SE3PlanarTrajectory {
 public:
  SE3EightTrajectory(Scalar T) : SE3PlanarTrajectory(T) {}

 protected:
  void sampleTrajectory(Scalar t, Vector3_<Scalar>& pos, Vector3_<Scalar>& vel,
                        Vector3_<Scalar>& acc) const override;
};
class SE3CircleTrajectory : public SE3PlanarTrajectory {
 public:
  SE3CircleTrajectory(Scalar T) : SE3PlanarTrajectory(T) {}

 protected:
  void sampleTrajectory(Scalar t, Vector3_<Scalar>& pos, Vector3_<Scalar>& vel,
                        Vector3_<Scalar>& acc) const override;
};

class SE3StraightTrajectory : public SE3PlanarTrajectory {
 public:
  SE3StraightTrajectory(Scalar T) : SE3PlanarTrajectory(T) {}

 protected:
  void sampleTrajectory(Scalar t, Vector3_<Scalar>& pos, Vector3_<Scalar>& vel,
                        Vector3_<Scalar>& acc) const override;
};

// Trajectory generated by integrating measurements in time
class MeasurementTrajectory : public Trajectory {
 public:
  MeasurementTrajectory(Scalar T) : Trajectory(T) {};

  // generate the ground truth trajectory (isometry and velocity) and
  // measurements
  virtual void generateData(
      Scalar freq,
      std::vector<std::tuple<IMUMeasurement<Scalar>, Vector3_<Scalar>,
                             Isometry3_<Scalar>>>& data) const;

 protected:
  void sampleMeasurement(Scalar t, Vector3_<Scalar>& acc,
                         Vector3_<Scalar>& ang_vel) const;

  // the internal frequency wich is used to generate the ground truth poses (it
  // should be high)
  Scalar freq_int_;

  std::vector<Isometry3_<Scalar>> poses_;
  std::vector<Vector3_<Scalar>> vels_;
};

class FakeImu {
 public:
  FakeImu(std::shared_ptr<Trajectory> traj_, Scalar freq,
          int seed = std::time(0))
      : freq_(freq), trajectory_(traj_), rnd_gen_(seed) {};

  void generateData(
      std::vector<std::tuple<IMUMeasurement<Scalar>, Vector3_<Scalar>,
                             Isometry3_<Scalar>>>& data,
      bool noise = false);

  inline const Trajectory& trajectory() const { return *trajectory_; }

  inline Scalar freq() const { return freq_; }

  inline const Vector3_<Scalar>& bias_acc() const { return ba_; }
  inline const Vector3_<Scalar>& bias_gyro() const { return bg_; }
  inline void bias_acc(const Vector3_<Scalar>& ba) { ba_ = ba; }
  inline void bias_gyro(const Vector3_<Scalar>& bg) { bg_ = bg; }

  inline Scalar& std_acc() { return std_acc_; }
  inline Scalar& std_gyro() { return std_gyro_; }
  inline Scalar& std_bias_acc() { return std_bias_acc_; }
  inline Scalar& std_bias_gyro() { return std_bias_gyro_; }

 protected:
  Scalar freq_;  // the frequency at which a new measurement becomes available

  Scalar std_acc_ = 0.00175f;
  Scalar std_gyro_ = 0.00175f;
  Scalar std_bias_acc_ = 0.00167f;
  Scalar std_bias_gyro_ = 0.00167f;

  std::shared_ptr<Trajectory> trajectory_;
  std::mt19937 rnd_gen_;

  Vector3_<Scalar> ba_ = Vector3_<Scalar>::Zero();
  Vector3_<Scalar> bg_ = Vector3_<Scalar>::Zero();
};
}  // namespace synthetic